/**
 * ENKO — легкий кастомний i18n (UA/RU) без важкого плагіна.
 *
 * Мова зберігається в кукі `enko_lang` (uk дефолт / ru). Перемикач у шапці — серверні
 * посилання `?lang=uk|ru` (init-хук ставить кукі й редіректить на чистий URL). Товари
 * беруть RU з meta `_enko_*_ru` (catalog-data.php); UI-рядки шаблонів — через `et()` за
 * картою `enko_i18n_map()`; великі тексти — через `enko_t($uk,$ru)`. Рядки enko.js
 * (каталог/кошик/тости) — через `window.ENKO_I18N` (enko_i18n_js_map()).
 *
 * @package enko-core
 */

if ( ! defined( 'ABSPATH' ) ) { exit; }

/** Поточна мова інтерфейсу: 'uk' | 'ru'. */
function enko_lang() {
	static $lang = null;
	if ( null !== $lang ) { return $lang; }
	$l    = isset( $_COOKIE['enko_lang'] ) ? sanitize_key( wp_unslash( $_COOKIE['enko_lang'] ) ) : 'uk';
	$lang = ( 'ru' === $l ) ? 'ru' : 'uk';
	return $lang;
}

/** Чи активна російська. */
function enko_is_ru() { return 'ru' === enko_lang(); }

/** Прямий вибір значення за мовою (для великих текстів / машинного RU). */
function enko_t( $uk, $ru = '' ) {
	return ( enko_is_ru() && '' !== (string) $ru ) ? $ru : $uk;
}

/** Переклад UI-рядка через карту (uk→ru). Якщо ключа нема — повертає оригінал (UA). */
function et( $uk ) {
	if ( ! enko_is_ru() ) { return $uk; }
	$map = enko_i18n_map();
	return isset( $map[ $uk ] ) ? $map[ $uk ] : $uk;
}

/**
 * Встановлення мови через ?lang=uk|ru → кукі + редірект на чистий URL.
 *
 * Закон України «Про забезпечення функціонування української мови як державної» (ст. 27):
 * сайт має ЗА ЗАМОВЧУВАННЯМ відкриватися українською. Тому:
 *  - українська — дефолт без кукі (прибираємо кукі);
 *  - вибір російської зберігається ЛИШЕ ДО КІНЦЯ ПОТОЧНОЇ ДОБИ (опівночі за часом сайту),
 *    після чого сайт знову відкривається українською.
 */
add_action( 'init', function () {
	if ( is_admin() || ! isset( $_GET['lang'] ) ) { return; }
	$l    = sanitize_key( wp_unslash( $_GET['lang'] ) );
	$l    = ( 'ru' === $l ) ? 'ru' : 'uk';
	$path = COOKIEPATH ? COOKIEPATH : '/';
	if ( 'ru' === $l ) {
		$tz  = function_exists( 'wp_timezone' ) ? wp_timezone() : new DateTimeZone( 'Europe/Kyiv' );
		$eod = ( new DateTime( 'tomorrow', $tz ) )->getTimestamp(); // найближча опівніч за часом сайту
		setcookie( 'enko_lang', 'ru', $eod, $path, COOKIE_DOMAIN );
		$_COOKIE['enko_lang'] = 'ru';
	} else {
		setcookie( 'enko_lang', '', time() - 3600, $path, COOKIE_DOMAIN ); // прибрати кукі → дефолт UA
		unset( $_COOKIE['enko_lang'] );
	}
	wp_safe_redirect( remove_query_arg( 'lang' ) );
	exit;
} );

/** <html lang> → ru-RU при російській. */
add_filter( 'language_attributes', function ( $out ) {
	if ( enko_is_ru() ) { $out = preg_replace( '/lang="[^"]*"/', 'lang="ru-RU"', $out ); }
	return $out;
} );

/** <title> сторінки → RU (заголовок із карти; товар — RU-назва з meta). */
add_filter( 'document_title_parts', function ( $parts ) {
	if ( ! enko_is_ru() || empty( $parts['title'] ) ) { return $parts; }
	if ( function_exists( 'is_product' ) && is_product() ) {
		$p = function_exists( 'wc_get_product' ) ? wc_get_product( get_queried_object_id() ) : null;
		if ( $p && $p->get_meta( '_enko_name_ru' ) ) { $parts['title'] = $p->get_meta( '_enko_name_ru' ); }
	} else {
		$parts['title'] = et( $parts['title'] );
	}
	return $parts;
}, 20 );

/** hreflang alternate (uk/ru) у <head>. */
add_action( 'wp_head', function () {
	$scheme = is_ssl() ? 'https' : 'http';
	$host   = isset( $_SERVER['HTTP_HOST'] ) ? $_SERVER['HTTP_HOST'] : wp_parse_url( home_url(), PHP_URL_HOST );
	$path   = strtok( isset( $_SERVER['REQUEST_URI'] ) ? $_SERVER['REQUEST_URI'] : '/', '?' );
	$cur    = $scheme . '://' . $host . $path;
	echo "\n<link rel=\"alternate\" hreflang=\"uk\" href=\"" . esc_url( add_query_arg( 'lang', 'uk', $cur ) ) . "\" />";
	echo "\n<link rel=\"alternate\" hreflang=\"ru\" href=\"" . esc_url( add_query_arg( 'lang', 'ru', $cur ) ) . "\" />\n";
}, 5 );

/** Повна карта uk→ru (шаблони + JS + кабінет) — спільна для T() у скриптах і DOM-перекладача. */
function enko_i18n_full_map() {
	static $m = null;
	if ( null !== $m ) { return $m; }
	$m = array_merge( enko_i18n_map(), enko_i18n_js_map(), enko_i18n_cabinet_map() );
	return $m;
}

/** window.ENKO_I18N (повна карта) — лише на ru, перед enko-js. Прототипні скрипти
 * (enko.js/home-r1.js/home-r2.js) перекладають свої рядки в ДЖЕРЕЛІ через T(s). */
add_action( 'wp_enqueue_scripts', function () {
	if ( ! enko_is_ru() ) { return; }
	wp_add_inline_script( 'enko-js', 'window.ENKO_I18N = ' . wp_json_encode( enko_i18n_full_map() ) . ';', 'before' );
}, 24 );

